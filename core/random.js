export function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function takeRandom(arr, n) {
  const a = shuffle(arr);
  return a.slice(0, Math.min(n, a.length));
}